// `pnpm db:types`: regenerate TypeScript types from the LOCAL database schema.
// A Node script instead of `>` redirection so it behaves the same in cmd, PowerShell and bash.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../packages/shared/src/database.types.ts', import.meta.url));

const types = execSync('supabase gen types typescript --local --schema public', {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'inherit'],
});

writeFileSync(out, `// Generated by \`pnpm db:types\`. Do not edit by hand.\n${types}`);
execSync(`prettier --write "${out}"`, { stdio: 'ignore' });
console.log(`Wrote ${out}`);
